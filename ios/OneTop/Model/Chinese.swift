        for (pattern, template) in patterns {
            if let match = en.wholeMatch(of: pattern) {
                var out = template
                for (i, part) in match.output.dropFirst().enumerated() {
                    out = out.replacingOccurrences(of: "{\(i)}", with: part.substring.map(String.init) ?? "")
                }
                return out
            }
        }
        return en
